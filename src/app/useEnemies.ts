import { useEffect, useState } from "react";
import type { EnemyType } from "../calculator/weapon.ts";

export interface Enemy {
  name: string;
  npcParamIds: number[];
  hp: number;
  /** Physical, magic, fire, lightning, holy */
  defense: number[];
  /**
   * Its HP (unrounded) and defenses in NG+ (journey 2), if it has an NG+ scaling effect, and its HP multiplier in
   * NG+ once Promised Consort Radahn has been beaten in an earlier journey, if any
   */
  ngPlus?: { hp: number; defense: number[]; radahnHpRate?: number };
  /** Standard, slash, strike, pierce, magic, fire, lightning, holy (percent) */
  negation: number[];
  /** Types some weapons and buffs do more damage to, e.g. "dragon" */
  types?: EnemyType[];
  /** True for allies, summonable helpers, and friendly or story state copies of NPCs */
  friendly?: boolean;
  boss?: boolean;
  /** True for wildlife, e.g. deer and eagles */
  neutral?: boolean;
  /** Damage multiplier for critical hits, if not 1 (e.g. 0.7 for Crucible Knights) */
  criticalDamageRate?: number;
  /** Poise damage multiplier, if not 1 (e.g. 0.2 for ancient dragons), from its permanent SpEffects */
  poiseDamageRate?: number;
  /** How its poise differs otherwise, e.g. only on some body parts */
  poiseNote?: string;
  /** Damage multiplier on its weak spot from every attack, if noted (e.g. 3 for Smith Golems) */
  weakPartDamageRate?: number;
  /** The ripostes the player can do to it (e.g. ["Large Riposte"]), none if it can't be riposted */
  ripostes: string[];
  /** When some of its ripostes apply, e.g. { "Small Riposte": "when they fall from their horse" } */
  riposteNotes?: Record<string, string>;
}

export interface EnemyArea {
  name: string;
  region: string;
  /** The defenses most of the area's enemies have (physical, magic, fire, lightning, holy) */
  defense: number[];
  /** The same in NG+ (journey 2) */
  ngPlusDefense: number[];
  /** True for areas in the Realm of Shadow, where the Scadutree Blessing applies */
  dlc?: boolean;
  enemies: Enemy[];
}

/** Uniquely identifies an enemy within its area */
export function getEnemyKey(enemy: Enemy) {
  return `${enemy.name}|${enemy.npcParamIds[0]}${enemy.friendly ? "|friendly" : ""}`;
}

export const maxNgPlus = 7;

/**
 * Multipliers on NG+ HP and defenses for each later journey, by NG+ level (ClearCountCorrectParam
 * rows 1-7, the same for every defense)
 */
const ngPlusRates = [
  { hp: 1, defense: 1 },
  { hp: 1, defense: 1 },
  { hp: 1.1, defense: 1.025 },
  { hp: 1.15, defense: 1.05 },
  { hp: 1.2, defense: 1.1 },
  { hp: 1.3, defense: 1.15 },
  { hp: 1.35, defense: 1.2 },
  { hp: 1.4, defense: 1.3 },
] as const;

/** @returns "NG", "NG+", "NG+2", etc. */
export function getNgPlusLabel(ngPlus: number) {
  return ngPlus === 0 ? "NG" : ngPlus === 1 ? "NG+" : `NG+${ngPlus}`;
}

/**
 * @returns an enemy's HP and defenses at an NG+ level (0 for NG). Enemies with no NG+ scaling
 * effect (mostly wildlife) start from their NG stats, but later journeys still scale them.
 */
export function getEnemyStats(enemy: Enemy, ngPlus: number, radahnBeaten: boolean) {
  if (ngPlus === 0) return { hp: enemy.hp, defense: enemy.defense };
  const {
    hp,
    defense,
    radahnHpRate = 1,
  } = enemy.ngPlus ?? { hp: enemy.hp, defense: enemy.defense };
  const rates = ngPlusRates[ngPlus];
  return {
    // (NG+ HP is unrounded: the game rounds down after every multiplier)
    hp: Math.floor(hp * (radahnBeaten ? radahnHpRate : 1) * rates.hp),
    defense: defense.map((value) => value * rates.defense),
  };
}

/** @returns the defenses most of an area's enemies have at an NG+ level (0 for NG) */
export function getAreaDefense(area: EnemyArea, ngPlus: number) {
  if (ngPlus === 0) return area.defense;
  return area.ngPlusDefense.map((defense) => defense * ngPlusRates[ngPlus].defense);
}

let enemyAreasPromise: Promise<EnemyArea[]> | undefined;

/**
 * Loads the enemy defense data generated by scripts/build_enemy_data.py
 */
/** @returns the label of the group an enemy is listed in */
export function getEnemyCategory(enemy: Enemy) {
  if (enemy.friendly) return "Friendly";
  if (enemy.boss) return "Bosses";
  if (enemy.neutral) return "Neutral";
  return "Enemies";
}

export default function useEnemies() {
  const [areas, setAreas] = useState<EnemyArea[]>([]);
  const [error, setError] = useState<Error>();

  useEffect(() => {
    enemyAreasPromise ??= fetch("/enemies.json")
      .then((res) => res.json())
      .then((data: { areas: EnemyArea[] }) => data.areas);
    enemyAreasPromise.then(setAreas).catch(setError);
  }, []);

  return { areas, error };
}
