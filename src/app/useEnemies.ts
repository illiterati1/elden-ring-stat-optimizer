import { useEffect, useState } from "react";
import type { EnemyType } from "../calculator/weapon.ts";
import { debug } from "./uiUtils.ts";

export interface Enemy {
  name: string;
  npcParamIds: number[];
  hp: number;
  /** Physical, magic, fire, lightning, holy */
  defense: number[];
  /** Standard, slash, strike, pierce, magic, fire, lightning, holy (percent) */
  negation: number[];
  /** Types some weapons and buffs do more damage to, e.g. "dragon" */
  types?: EnemyType[];
  /** True for allies, summonable helpers, and friendly or story state copies of NPCs */
  friendly?: boolean;
  boss?: boolean;
  /** True for wildlife, e.g. deer and eagles */
  neutral?: boolean;
  /** Damage multiplier for critical hits, if not 1 (e.g. 0.7 for Crucible Knights) */
  criticalDamageRate?: number;
  /** The ripostes the player can do to it (e.g. ["Large Riposte"]), none if it can't be riposted */
  ripostes: string[];
  /** When some of its ripostes apply, e.g. { "Small Riposte": "when they fall from their horse" } */
  riposteNotes?: Record<string, string>;
}

export interface EnemyArea {
  name: string;
  region: string;
  /** The defenses most of the area's enemies have (physical, magic, fire, lightning, holy) */
  defense: number[];
  enemies: Enemy[];
}

/** Uniquely identifies an enemy within its area */
export function getEnemyKey(enemy: Enemy) {
  return `${enemy.name}|${enemy.npcParamIds[0]}${enemy.friendly ? "|friendly" : ""}`;
}

let enemyAreasPromise: Promise<EnemyArea[]> | undefined;

/**
 * Loads the enemy defense data generated by scripts/build_enemy_data.py
 */
/** @returns the label of the group an enemy is listed in when every enemy is (debug mode) */
export function getEnemyCategory(enemy: Enemy) {
  if (enemy.friendly) return "Friendly";
  if (enemy.boss) return "Bosses";
  if (enemy.neutral) return "Neutral";
  return "Enemies";
}

export default function useEnemies() {
  const [areas, setAreas] = useState<EnemyArea[]>([]);
  const [error, setError] = useState<Error>();

  useEffect(() => {
    enemyAreasPromise ??= fetch("/enemies.json")
      .then((res) => res.json())
      .then((data: { areas: EnemyArea[] }) =>
        // Only bosses for now, since other enemies' regions aren't reliable yet (all of them in
        // debug mode)
        debug
          ? data.areas
          : data.areas
              .map((area) => ({ ...area, enemies: area.enemies.filter((enemy) => enemy.boss) }))
              .filter((area) => area.enemies.length > 0),
      );
    enemyAreasPromise.then(setAreas).catch(setError);
  }, []);

  return { areas, error };
}
