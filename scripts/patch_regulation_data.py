"""
Patch public/regulation-vanilla-v1.17.js (generated by the original calculator's build script) with
each weapon's status effect scaling curves (EquipParamWeapon correctType_Poison, _Blood, _Sleep,
_Madness), which it only records for weapons with their own status buildup. Others can still build
up status from their ammunition, e.g. the Serpent Bow's poison curve (CalcCorrectGraph 5) applies
to Serpent Arrows.

Also adds each weapon's damage multipliers against enemy types (EquipParamWeapon weakA-D_DamageRate,
e.g. the Golden Epitaph's ×1.3 against those who live in death) as enemyTypeRates, and its weight
(EquipParamWeapon weight), for the Blue Dancer Charm's equip weight.

Usage:
  python3 -I scripts/patch_regulation_data.py <ELDEN RING Game dir>

Inputs:
  - data/EquipParamWeapon-vanilla.csv and data/CalcCorrectGraph-vanilla.csv, decoded with
    extract_param.py
  - <Game>/msg/engus/item-msgbnd-dcx and item_dlc02-msgbnd-dcx, unpacked with WitchyBND, for
    weapon names

Safe to run more than once.
"""

import csv
import json
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from build_moveset_data import read_weapon_rows, read_weapons  # noqa: E402

# AttackPowerType of each status effect's correctType field
STATUS_CORRECT_FIELDS = {
    5: "correctType_Poison",
    7: "correctType_Blood",
    9: "correctType_Sleep",
    10: "correctType_Madness",
}

# The curve status effects use unless a weapon says otherwise
DEFAULT_STATUS_GRAPH = 6

UNIQUE_AFFINITY_ID = -1

# EquipParamWeapon damage multiplier fields for each enemy type (see build_enemy_data.py's
# ENEMY_TYPES)
ENEMY_TYPE_RATE_FIELDS = {
    "star": "weakA_DamageRate",
    "death": "weakB_DamageRate",
    "ancientDragon": "weakC_DamageRate",
    "dragon": "weakD_DamageRate",
}


def main():
    game_dir = sys.argv[1]
    project_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    path = os.path.join(project_dir, "public", "regulation-vanilla-v1.17.js")
    with open(path, encoding="utf-8") as f:
        regulation = json.load(f)

    base_rows = read_weapons(game_dir, project_dir)
    rows = read_weapon_rows(project_dir)
    with open(os.path.join(project_dir, "data", "CalcCorrectGraph-vanilla.csv"), encoding="utf-8") as f:
        graphs = {int(row["id"]): row for row in csv.DictReader(f)}

    patched = []
    for weapon in regulation["weapons"]:
        base = base_rows.get(weapon["weaponName"])
        if base is None:
            continue
        row = rows.get(int(base["id"]) + max(weapon["affinityId"], 0) * 100)
        if row is None:
            continue
        graph_ids = weapon.setdefault("calcCorrectGraphIds", {})
        for status_type, field in STATUS_CORRECT_FIELDS.items():
            graph_id = int(row[field])
            if graph_id and graph_id != DEFAULT_STATUS_GRAPH and str(status_type) not in graph_ids:
                graph_ids[str(status_type)] = graph_id
                patched.append(f"{weapon['name']}: {field} {graph_id}")
        rates = {
            enemy_type: float(row[field])
            for enemy_type, field in ENEMY_TYPE_RATE_FIELDS.items()
            if float(row[field]) != 1
        }
        if rates != weapon.get("enemyTypeRates", {}):
            patched.append(f"{weapon['name']}: enemyTypeRates {rates}")
        if rates:
            weapon["enemyTypeRates"] = rates
        else:
            weapon.pop("enemyTypeRates", None)
        weight = round(float(row["weight"]), 2)
        if weight != weapon.get("weight"):
            patched.append(f"{weapon['name']}: weight {weight}")
        weapon["weight"] = weight

    # Add any curves weapons now use that the data doesn't have, in the same format
    used = {
        graph_id for weapon in regulation["weapons"] for graph_id in weapon["calcCorrectGraphIds"].values()
    }
    for graph_id in sorted(used):
        if str(graph_id) not in regulation["calcCorrectGraphs"]:
            row = graphs[graph_id]
            regulation["calcCorrectGraphs"][str(graph_id)] = [
                {
                    "maxVal": float(row[f"stageMaxVal{i}"]),
                    "maxGrowVal": float(row[f"stageMaxGrowVal{i}"]) / 100,
                    "adjPt": float(row[f"adjPt_maxGrowVal{i}"]),
                }
                for i in range(5)
            ]
            patched.append(f"curve {graph_id}")

    with open(path, "w", encoding="utf-8") as f:
        json.dump(regulation, f, separators=(",", ":"), ensure_ascii=False)
    print(f"{len(patched)} changes -> {path}")
    for change in patched:
        print(f"  {change}")


if __name__ == "__main__":
    main()
